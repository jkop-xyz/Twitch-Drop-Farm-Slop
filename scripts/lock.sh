#!/bin/sh
# Regenerate requirements.lock (pinned runtime deps) inside the same Python image the
# Dockerfile uses, so the pins match what ships. Run after changing dependencies in pyproject.toml.
set -eu
cd "$(dirname "$0")/.."
{
  echo "# Pinned runtime dependencies. Generated by scripts/lock.sh from pyproject.toml; do not edit."
  docker run --rm -v "$PWD/pyproject.toml:/src/pyproject.toml:ro" -w /src python:3.13-slim sh -c \
    "pip install -q --root-user-action=ignore pip-tools && pip-compile -q --strip-extras --no-header --output-file=- pyproject.toml"
} > requirements.lock.tmp
mv requirements.lock.tmp requirements.lock
echo "requirements.lock updated"
